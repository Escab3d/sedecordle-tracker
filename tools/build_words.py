"""Generate extension/lib/words.js from data/answers.txt and data/allowed.txt.

The order of answers.txt must match the site exactly: answers are picked by index.
Run from the project root:  python tools/build_words.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


def load(name):
    words = (ROOT / "data" / name).read_text(encoding="utf-8").split()
    assert all(len(w) == 5 and w.isalpha() and w.islower() for w in words), name
    return words


answers = load("answers.txt")
allowed = load("allowed.txt")
assert len(set(answers)) == len(answers)
assert not set(answers) & set(allowed)

out = ROOT / "extension" / "lib" / "words.js"
out.write_text(
    "// GENERATED by tools/build_words.py from data/*.txt. Do not edit by hand.\n"
    "// answers: the site's answer list in its original order (index-sensitive).\n"
    "// allowed: extra valid guesses that are never answers.\n"
    "globalThis.SEDEC_WORDS = {\n"
    f"  answers: {json.dumps(' '.join(answers))}.split(' '),\n"
    f"  allowed: {json.dumps(' '.join(allowed))}.split(' ')\n"
    "};\n",
    encoding="utf-8",
)
print(f"wrote {out} ({len(answers)} answers, {len(allowed)} allowed)")
